import fs from 'node:fs'
import path from 'node:path'

const rootDir = process.cwd()
const electronDir = path.join(rootDir, 'electron')
const outputPath = path.join(electronDir, 'embeddedUpdateToken.generated.cjs')

const githubToken = String(process.env.BIZSUIT_UPDATE_GITHUB_TOKEN || '').trim()
const tokenRequired = process.env.BIZSUIT_UPDATE_TOKEN_REQUIRED === '1'
if (tokenRequired && !githubToken) {
  throw new Error('BIZSUIT_UPDATE_GITHUB_TOKEN is required for this build.')
}
const contents = `// Generated by scripts/generate-update-config.mjs. Do not commit.
module.exports = {
  githubToken: ${JSON.stringify(githubToken)},
};
`

fs.mkdirSync(electronDir, { recursive: true })
fs.writeFileSync(outputPath, contents, 'utf8')

if (githubToken) {
  console.log('[update-config] Embedded GitHub update token into Electron package.')
} else {
  console.log('[update-config] No BIZSUIT_UPDATE_GITHUB_TOKEN set; generated empty embedded update token.')
}
